DESTINATIONS: dict[str, dict] = {d["slug"]: d for d in D}

MONTHS = ["January", "February", "March", "April", "May", "June", "July", "August", "September", "October",
          "November", "December"]


def find_destination(name: str) -> dict | None:
    key = normalise(name)
    slug = key.replace(" ", "-")
    if slug in DESTINATIONS:
        return DESTINATIONS[slug]
    for d in D:
        if key == d["name"].lower() or key in d["name"].lower() or d["slug"] in slug:
            return d
    return None


def parse_month(value) -> int | None:
    if isinstance(value, int):
        return value if 1 <= value <= 12 else None
    text = str(value).strip().lower()
    if text.isdigit():
        return parse_month(int(text))
    for i, m in enumerate(MONTHS, 1):
        if text[:3] == m[:3].lower():
            return i
    return None
